// @vitest-environment happy-dom
// The authored Angular examples of the docs, mounted through the same AOT
// runtime as the site: every example renders its Minerva components, and the
// interactive ones write their events back into the displayed state.
import "@angular/compiler";
import { existsSync } from "node:fs";
import { resolve } from "node:path";
import { act, render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { MemoryRouter } from "react-router";
import { afterEach, beforeAll, describe, expect, it, vi } from "vitest";
import { ConfigProvider } from "minerva-design";
import { SiteProviders, setupI18n } from "../../test/utils";
import { getDocPage } from "../registry";
import AngularDemo from "./AngularDemo";
import AngularSection from "./AngularSection";
import { angularExamples, type AngularExample } from "./examples";
import type { AngularIsland, AngularSettings } from "./runtime";

// generated by ngc during the docs build/typecheck (gitignored)
const compiled = existsSync(resolve(import.meta.dirname, ".aot/examples.js"));

const SETTINGS: AngularSettings = {
  theme: "light",
  palette: null,
  language: "en",
};

const mounted: { island: AngularIsland; root: HTMLElement }[] = [];

const exampleOf = (page: string, id: string): AngularExample => {
  const example = angularExamples[page]?.find((item) => item.id === id);
  if (!example) throw new Error(`no Angular example ${page}/${id}`);
  return example;
};

const mount = async (example: AngularExample) => {
  const { mountAngularExample } = await import("./runtime");
  const root = document.createElement("div");
  document.body.append(root);
  const island = await mountAngularExample(root, example, SETTINGS, {
    theme() {},
    palette() {},
  });
  mounted.push({ island, root });
  return root;
};

const show = async (page: string, id: string) => {
  const root = await mount(exampleOf(page, id));
  return { root, view: within(root), user: userEvent.setup() };
};

beforeAll(async () => {
  await setupI18n();
  // NG0912 (component id collisions between the islands) is harmless here
  const warn = console.warn;
  vi.spyOn(console, "warn").mockImplementation((...args: unknown[]) => {
    if (!String(args[0]).includes("NG0912")) warn(...args);
  });
});

afterEach(() => {
  for (const { island, root } of mounted.splice(0)) {
    island.destroy();
    root.remove();
  }
  document.body.innerHTML = "";
});

describe.skipIf(!compiled)("Angular documentation examples", () => {
  const pages = Object.keys(angularExamples).filter(
    (page) => page !== "monaco-code-editor",
  );

  it.each(pages)(
    "%s: every example renders its components",
    async (page) => {
      for (const example of angularExamples[page]!) {
        const root = await mount(example);
        expect(
          root.querySelector("mn-docs-example [data-minerva]"),
          `${page}/${example.id}`,
        ).not.toBeNull();
      }
    },
    // the first page also pays for the cold Angular bootstrap
    30_000,
  );

  it("button counter counts clicks", async () => {
    const { view, user } = await show("button", "actions-and-feedback");
    const button = view.getByRole("button", { name: "Click me" });
    await user.click(button);
    await user.click(button);
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Clicked 2 times"),
    );
  });

  it("native form buttons preview, submit and reset", async () => {
    const { view, user } = await show("button", "native-form-buttons");
    const title = view.getByRole("textbox", { name: "Title" });
    await user.clear(title);
    await user.type(title, "Minerva");
    await user.click(view.getByRole("button", { name: "Preview" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent(
        "Preview opened (form not submitted)",
      ),
    );
    await user.click(view.getByRole("button", { name: "Save" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Submitted Minerva"),
    );
    await user.click(view.getByRole("button", { name: "Reset" }));
    await waitFor(() => expect(title).toHaveValue("Draft"));
    expect(view.getByRole("status")).toHaveTextContent("Reset");
  });

  it("input validation blocks an empty submit, then submits and resets", async () => {
    const { view, user } = await show(
      "input",
      "native-validation-and-field-context",
    );
    await user.click(view.getByRole("button", { name: "Subscribe" }));
    const email = view.getByRole("textbox", { name: /Email/ });
    await waitFor(() => expect(email).toHaveAttribute("aria-invalid", "true"));
    expect(view.getByRole("status")).toHaveTextContent("Not submitted");
    await user.type(email, "ada@example.com");
    await user.click(view.getByRole("button", { name: "Subscribe" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent(
        "Submitted ada@example.com",
      ),
    );
    await user.click(view.getByRole("button", { name: "Reset" }));
    await waitFor(() => expect(email).toHaveValue(""));
    expect(view.getByRole("status")).toHaveTextContent("Reset");
  });

  it("input clears the search and reveals the password", async () => {
    const { view, user } = await show(
      "input",
      "clear-password-and-character-count",
    );
    await user.click(view.getByRole("button", { name: "Clear search" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Search: (empty)"),
    );
    await user.click(view.getByRole("button", { name: "Show password" }));
    const password = view.getByLabelText("Password", { exact: true });
    await waitFor(() => expect(password).toHaveAttribute("type", "text"));
    expect(password).toHaveValue("secret-pass");
  });

  it("confirm provider queues two confirmations", async () => {
    const { view, user } = await show("confirm", "queued-confirmations");
    await user.click(
      view.getByRole("button", { name: "Queue two confirmations" }),
    );
    const first = await screen.findByRole("alertdialog", {
      name: "Delete draft?",
    });
    await user.click(within(first).getByRole("button", { name: "Confirm" }));
    const second = await screen.findByRole("alertdialog", {
      name: "Archive project?",
    });
    await user.click(within(second).getByRole("button", { name: "Cancel" }));
    await waitFor(() => expect(screen.queryByRole("alertdialog")).toBeNull());
  });

  it("confirm dialog keeps Cancel disabled while loading, then completes", async () => {
    const { view, user } = await show(
      "confirm",
      "controlled-loading-and-recovery",
    );
    await user.click(view.getByRole("button", { name: "Preview processing" }));
    const dialog = await screen.findByRole("alertdialog");
    await user.click(within(dialog).getByRole("button", { name: "Confirm" }));
    await waitFor(() =>
      expect(
        within(dialog).getByRole("button", { name: "Cancel" }),
      ).toBeDisabled(),
    );
    await user.click(screen.getByRole("button", { name: "Complete request" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Request completed"),
    );
  });

  it("menu radio group writes the density back", async () => {
    const { view, user } = await show("menu", "named-groups-and-radio-choices");
    await user.click(view.getByRole("button", { name: "Display density" }));
    expect(
      await screen.findByRole("group", { name: "Density" }),
    ).toBeInTheDocument();
    await user.click(screen.getByRole("menuitemradio", { name: "Compact" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Density: compact"),
    );
  });

  it("context menu toggles a checked item", async () => {
    const { view, user } = await show("menu", "context-menu-and-checked-items");
    await user.pointer({
      keys: "[MouseRight]",
      target: view.getByRole("button", { name: "Right-click here" }),
    });
    await user.click(
      await screen.findByRole("menuitemcheckbox", {
        name: "Show hidden files",
      }),
    );
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent("Hidden: false"),
    );
  });

  it("nested menu reports the leaf action and the expanded items", async () => {
    const { view, user } = await show(
      "menu",
      "nested-actions-and-expanded-state",
    );
    await user.click(view.getByRole("button", { name: "File actions" }));
    await user.click(await screen.findByRole("menuitem", { name: "Export" }));
    await user.click(await screen.findByRole("menuitem", { name: "CSV" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent(
        "CSV · Expanded: export",
      ),
    );
  });

  it("table selects a row and keeps the custom colspan", async () => {
    const { view, user } = await show(
      "table",
      "semantic-composition-and-merged-cells",
    );
    const table = view.getByRole("table", { name: "Project summary" });
    await user.click(within(table).getByRole("button", { name: "Select" }));
    await waitFor(() =>
      expect(table.querySelector("tbody tr")).toHaveAttribute(
        "aria-selected",
        "true",
      ),
    );
    expect(
      within(table).getByRole("cell", {
        name: "Custom content spans both columns.",
      }),
    ).toHaveAttribute("colspan", "2");
  });

  it("config provider toggles its scope but not the explicit nested one", async () => {
    const { view, user } = await show(
      "config-provider",
      "reactive-nested-configuration",
    );
    await user.click(view.getByRole("button", { name: "Toggle scoped theme" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent(
        "Scope: dark / default",
      ),
    );
    expect(
      view
        .getByRole("button", { name: "Nested light tech button" })
        .closest("mn-config"),
    ).toHaveAttribute("data-theme", "light");
    await user.click(view.getByRole("button", { name: "Reset scope" }));
    await waitFor(() =>
      expect(view.getByRole("status")).toHaveTextContent(
        "Scope: light / default",
      ),
    );
  });

  it("the docs wrapper follows the site theme", async () => {
    const example = exampleOf("button", "actions-and-feedback");
    const { container, rerender } = render(
      <ConfigProvider theme="light">
        <AngularDemo example={example} />
      </ConfigProvider>,
    );
    const demo = container.querySelector("[data-angular-demo]")!;
    await waitFor(() => expect(demo).toHaveAttribute("aria-busy", "false"), {
      timeout: 10000,
    });
    expect(demo.querySelector("mn-config")).toHaveAttribute(
      "data-theme",
      "light",
    );
    await act(async () => {
      rerender(
        <ConfigProvider theme="dark">
          <AngularDemo example={example} />
        </ConfigProvider>,
      );
    });
    await waitFor(() =>
      expect(demo.querySelector("mn-config")).toHaveAttribute(
        "data-theme",
        "dark",
      ),
    );
    expect(screen.queryByText("Unable to load this example")).toBeNull();
  });

  it("the Angular section lists every example and the Angular API", async () => {
    const meta = getDocPage("button")!;
    const { container } = render(
      <SiteProviders>
        <MemoryRouter>
          <AngularSection meta={meta} />
        </MemoryRouter>
      </SiteProviders>,
    );
    const demos = container.querySelectorAll("[data-angular-demo]");
    expect(demos).toHaveLength(angularExamples.button!.length);
    for (const example of angularExamples.button!) {
      expect(
        container.querySelector(`#angular-demo-${example.id}`),
      ).not.toBeNull();
    }
    expect(
      screen.getByRole("heading", { name: "Angular API" }),
    ).toBeInTheDocument();
    expect(container.querySelector("table")).toHaveTextContent("loading");
    await waitFor(
      () => {
        for (const demo of demos)
          expect(demo).toHaveAttribute("aria-busy", "false");
      },
      { timeout: 10000 },
    );
    expect(screen.queryByText("Unable to load this example")).toBeNull();
  });
});
