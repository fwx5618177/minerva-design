// Writes the Volar `GlobalComponents` typings of the Vue plugins:
// - src/global.ts (`minerva-design/vue/global`): the components registered
//   by `app.use(MinervaVue)` (`<MnButton>`...), every component but the charts
// - src/charts-global.ts (`minerva-design/vue/charts-global`): the charts
//   registered by the opt-in `app.use(MinervaVueCharts)` (`<MnLineChart>`...)
// - src/icons-global.ts (`minerva-design/vue/icons-global`): the icon
//   components registered by the opt-in `app.use(MinervaVueIcons)`
//   (`<MnIcon>`, `<MnIconCanvas>`, `<MnDynamicIcon>`)
// The component names are the PascalCase value exports of the renderer
// (static read of its barrels, like the contracts generator);
// src/plugins.test.ts checks them against the runtime plugins.
//   node scripts/generate-global.mjs          (write)
//   node scripts/generate-global.mjs --check  (exit 1 when stale)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  readValueExports,
  readVue,
} from "../../../tools/generate-contracts.mjs";

const OUTPUT = fileURLToPath(new URL("../src/global.ts", import.meta.url));
const CHARTS_OUTPUT = fileURLToPath(
  new URL("../src/charts-global.ts", import.meta.url),
);
const ICONS_OUTPUT = fileURLToPath(
  new URL("../src/icons-global.ts", import.meta.url),
);

/** The components of `MinervaVueIcons` (the named icons are not registered) */
export const ICON_PLUGIN_COMPONENTS = ["DynamicIcon", "Icon", "IconCanvas"];

/** PascalCase value exports that are not components */
export const NOT_COMPONENTS = new Set([
  "MinervaVue",
  "MinervaVueCharts",
  "MinervaVueIcons",
]);

const components = (names) =>
  [...names]
    .filter(
      (name) =>
        /^[A-Z][A-Za-z0-9]*[a-z][A-Za-z0-9]*$/.test(name) &&
        !NOT_COMPONENTS.has(name),
    )
    .filter((name) => name !== "MonacoCodeEditor")
    .sort();

/** The chart components (`MinervaVueCharts`) */
export function chartComponentNames() {
  return components(readValueExports(["packages/vue/src/charts.ts"]));
}

/** The components of `MinervaVue` (every component but the charts) */
export function componentNames() {
  const charts = new Set(chartComponentNames());
  return components(readVue()).filter((name) => !charts.has(name));
}

const typings = (
  header,
  from,
  names,
) => `// Generated by scripts/generate-global.mjs: do not edit.
${header}
import type * as Minerva from "${from}";

declare module "vue" {
  export interface GlobalComponents {
${names.map((name) => `    Mn${name}: typeof Minerva.${name};`).join("\n")}
  }
}

export {};
`;

async function formatted(text, filepath) {
  const options = (await resolveConfig(filepath)) ?? {};
  return format(text, { ...options, filepath });
}

export async function generateGlobal() {
  return formatted(
    typings(
      `// Volar typings of the components registered by \`app.use(MinervaVue)\`
// (default prefix "Mn"): add "minerva-design/vue/global" to the "types" of
// tsconfig.json, or \`import type {} from "minerva-design/vue/global"\`.
// The charts have their own typings: "minerva-design/vue/charts-global".`,
      "./index",
      componentNames(),
    ),
    OUTPUT,
  );
}

export async function generateChartsGlobal() {
  return formatted(
    typings(
      `// Volar typings of the charts registered by \`app.use(MinervaVueCharts)\`
// (minerva-design/vue/charts, default prefix "Mn"): add
// "minerva-design/vue/charts-global" to the "types" of tsconfig.json, or
// \`import type {} from "minerva-design/vue/charts-global"\`.`,
      "./charts",
      chartComponentNames(),
    ),
    CHARTS_OUTPUT,
  );
}

export async function generateIconsGlobal() {
  return formatted(
    typings(
      `// Volar typings of the icon components registered by
// \`app.use(MinervaVueIcons)\` (minerva-design/vue/icons, default prefix "Mn"):
// add "minerva-design/vue/icons-global" to the "types" of tsconfig.json, or
// \`import type {} from "minerva-design/vue/icons-global"\`.`,
      "./icons",
      ICON_PLUGIN_COMPONENTS,
    ),
    ICONS_OUTPUT,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const outputs = [
    [OUTPUT, await generateGlobal()],
    [CHARTS_OUTPUT, await generateChartsGlobal()],
    [ICONS_OUTPUT, await generateIconsGlobal()],
  ];
  if (process.argv.includes("--check")) {
    const stale = outputs.filter(
      ([file, next]) =>
        !existsSync(file) || readFileSync(file, "utf8") !== next,
    );
    if (stale.length > 0) {
      console.error(
        `${stale.map(([file]) => file).join(", ")} stale: run node scripts/generate-global.mjs`,
      );
      process.exit(1);
    }
  } else {
    for (const [file, next] of outputs) writeFileSync(file, next);
  }
}
