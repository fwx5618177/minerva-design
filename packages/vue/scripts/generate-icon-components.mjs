// Writes src/icon/icons.ts: one named Vue component per built-in icon of
// minerva-design/icons (`searchIcon` -> `SearchIcon`), in the order of the
// React components (packages/icons/src/react/icons.ts, generated from the
// icon files). Run after adding or renaming an icon (and `pnpm --filter
// @minerva/icons gen`); src/icon/icon.test.ts fails while it is stale.
//   node scripts/generate-icon-components.mjs          (write)
//   node scripts/generate-icon-components.mjs --check  (exit 1 when stale)
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const SOURCE = fileURLToPath(
  new URL("../../icons/src/react/icons.ts", import.meta.url),
);
export const ICON_COMPONENTS_OUTPUT = fileURLToPath(
  new URL("../src/icon/icons.ts", import.meta.url),
);

/** [component, icon constant] pairs of the React components */
export function iconComponentNames() {
  return [
    ...readFileSync(SOURCE, "utf8").matchAll(
      /export const (\w+) = \/\* @__PURE__ \*\/ createIcon\(\s*icons\.(\w+),?\s*\)/g,
    ),
  ].map(([, component, constant]) => [component, constant]);
}

export async function generateIconComponents() {
  const source = [
    "// Generated by scripts/generate-icon-components.mjs: do not edit.",
    "// One Vue component per built-in icon; unused ones are tree-shaken.",
    'import * as icons from "minerva-design/icons/core";',
    'import { createIcon } from "./createIcon";',
    "",
    ...iconComponentNames().map(
      ([component, constant]) =>
        `export const ${component} = /* @__PURE__ */ createIcon(icons.${constant});`,
    ),
    "",
  ].join("\n");
  const options = (await resolveConfig(ICON_COMPONENTS_OUTPUT)) ?? {};
  return format(source, { ...options, filepath: ICON_COMPONENTS_OUTPUT });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await generateIconComponents();
  if (process.argv.includes("--check")) {
    if (
      !existsSync(ICON_COMPONENTS_OUTPUT) ||
      readFileSync(ICON_COMPONENTS_OUTPUT, "utf8") !== next
    ) {
      console.error(
        "src/icon/icons.ts is stale: run node scripts/generate-icon-components.mjs",
      );
      process.exit(1);
    }
  } else {
    writeFileSync(ICON_COMPONENTS_OUTPUT, next);
  }
}
