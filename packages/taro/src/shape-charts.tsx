/** Default accessible name of a chart (like the web charts) */
const describe = (o: ShapeChartOptions): string => {
  switch (o.type) {
    case "pie":
      return o.rose
        ? "Rose chart"
        : (o.innerRadius ?? 0) > 0
          ? "Donut chart"
          : "Pie chart";
    case "radar":
      return "Radar chart";
    case "gauge":
      return o.label ? `Gauge: ${o.label}` : "Gauge";
    case "funnel":
      return "Funnel chart";
    case "treemap":
      return "Treemap";
    case "sankey":
      return "Sankey diagram";
    case "sunburst":
      return "Sunburst chart";
    case "radialBar":
      return "Radial bar chart";
    case "calendarHeatmap":
      return "Calendar heatmap";
    case "bullet":
      return "Bullet chart";
    case "chord":
      return "Chord diagram";
    default:
      return "Chart";
  }
};

/** Locates the canvas node, creates the engine on it and forwards the touches */
function ShapeChartBase({
  options,
  height,
  width = "100%",
  className,
  style,
  id,
  disableScroll,
  handleRef,
  ...handlers
}: ShapeChartBaseProps) {
  const generated = `mn-shape-chart-${useId().replace(/[^a-zA-Z0-9_-]/g, "")}`;
  const canvasId = id ?? generated;
  const tokens = useThemeTokens();
  const themeKey = JSON.stringify(tokens.css);
  const theme = useMemo<ChartThemeInput>(
    () => ({
      variables: Object.fromEntries(
        Object.entries(tokens.css).map(([key, value]) => [
          `--${key}`,
          String(value),
        ]),
      ),
      ...(tokens.css["font-family-sans"]
        ? { fontFamily: String(tokens.css["font-family-sans"]) }
        : {}),
    }),
    // tokens is a new object on every render of the provider
    [themeKey],
  );

  const hostRef = useRef<Host | null>(null);
  const chartRef = useRef<CanvasShapeChartInstance | null>(null);
  const rectRef = useRef({ left: 0, top: 0 });
  const optionsRef = useRef(options);
  const themeRef = useRef(theme);
  const handlersRef = useRef<Handlers>(handlers);
  const remeasureRef = useRef<() => void>(() => {});
  useEffect(() => {
    handlersRef.current = handlers;
  });

  // Mount: locate the canvas node once it is rendered, then draw on it
  useEffect(() => {
    let disposed = false;
    let timer: ReturnType<typeof setTimeout> | undefined;
    const offs: (() => void)[] = [];

    const measure = (done: (result: Measure | null) => void) => {
      const host = hostRef.current;
      const fromDom = () => {
        // H5: the 2D node is the <canvas> inside <taro-canvas-core>
        const canvas = isH5
          ? (host?.querySelector?.("canvas") as ChartCanvas | null)
          : null;
        const rect = canvas ? host?.getBoundingClientRect?.() : undefined;
        done(
          canvas && rect && rect.width > 0 && rect.height > 0
            ? {
                canvas,
                width: rect.width,
                height: rect.height,
                left: rect.left,
                top: rect.top,
              }
            : null,
        );
      };
      try {
        let query = Taro.createSelectorQuery?.();
        if (!query) return fromDom();
        const scope = queryScope(host);
        if (scope) query = query.in(scope as never);
        query
          .select(`#${canvasId}`)
          .fields({ node: true, size: true, rect: true })
          .exec((res: unknown) => {
            if (disposed) return;
            const found = (Array.isArray(res) ? res[0] : null) as QueryResult;
            const node = found?.node;
            if (
              node &&
              typeof node.getContext === "function" &&
              (found.width ?? 0) > 0 &&
              (found.height ?? 0) > 0
            )
              done({
                canvas: node as ChartCanvas,
                width: found.width ?? 0,
                height: found.height ?? 0,
                left: found.left ?? 0,
                top: found.top ?? 0,
              });
            else fromDom();
          });
      } catch {
        fromDom();
      }
    };

    const create = (m: Measure) => {
      rectRef.current = { left: m.left, top: m.top };
      const chart = createCanvasShapeChart({
        canvas: m.canvas,
        width: m.width,
        height: m.height,
        pixelRatio: pixelRatio(),
        options: optionsRef.current,
        theme: themeRef.current,
      });
      chartRef.current = chart;
      const h = () => handlersRef.current;
      offs.push(
        chart.on("hover", (event) => h().onHover?.(event)),
        chart.on("click", (event) => h().onClick?.(event)),
        chart.on("toggle", (event) => h().onToggle?.(event)),
        chart.on("drill", (event) => h().onDrill?.(event)),
      );
    };

    const locate = (attempt: number) => {
      if (disposed) return;
      measure((m) => {
        if (disposed || chartRef.current) return;
        if (m) create(m);
        else if (attempt < RETRIES)
          timer = setTimeout(() => locate(attempt + 1), RETRY_MS);
      });
    };

    remeasureRef.current = () => {
      if (disposed) return;
      if (!chartRef.current) {
        clearTimeout(timer);
        return locate(0);
      }
      measure((m) => {
        const chart = chartRef.current;
        if (!m || !chart || disposed) return;
        rectRef.current = { left: m.left, top: m.top };
        chart.resize(m.width, m.height, pixelRatio());
      });
    };

    const start = () => {
      if (disposed) return;
      // H5: wait for the first render of <taro-canvas-core>, which resets
      // the size of its inner canvas
      const ready = isH5 ? hostRef.current?.componentOnReady?.() : undefined;
      if (ready)
        ready.then(
          () => locate(0),
          () => locate(0),
        );
      else locate(0);
    };
    Taro.nextTick(start);

    const onWindowResize = () => remeasureRef.current();
    Taro.onWindowResize?.(onWindowResize);
    let observer: ResizeObserver | undefined;
    if (isH5 && typeof ResizeObserver !== "undefined") {
      const host = hostRef.current as unknown as Element | null;
      const box = host?.parentNode as Element | null | undefined;
      if (box) {
        let first = true;
        observer = new ResizeObserver(() => {
          if (first) first = false;
          else remeasureRef.current();
        });
        observer.observe(box);
      }
    }

    return () => {
      disposed = true;
      clearTimeout(timer);
      Taro.offWindowResize?.(onWindowResize);
      observer?.disconnect();
      offs.forEach((off) => off());
      chartRef.current?.destroy();
      chartRef.current = null;
      remeasureRef.current = () => {};
    };
    // Created once: the canvas id is fixed, the props are read through refs
  }, []);

  useEffect(() => {
    if (optionsRef.current === options) return;
    optionsRef.current = options;
    chartRef.current?.setOptions(options);
  }, [options]);

  useEffect(() => {
    if (themeRef.current === theme) return;
    themeRef.current = theme;
    chartRef.current?.setTheme(theme);
  }, [theme]);

  const sized = useRef(false);
  useEffect(() => {
    if (!sized.current) {
      sized.current = true;
      return;
    }
    Taro.nextTick(() => remeasureRef.current());
  }, [width, height]);

  useImperativeHandle(
    handleRef,
    () => ({
      getInstance: () => chartRef.current,
      resize: () => remeasureRef.current(),
    }),
    [],
  );

  // Stable props: on H5 every re-render of <taro-canvas-core> clears the canvas
  const canvasProps = useMemo(() => {
    let lastTouch = 0;
    const origin = () => {
      const rect = isH5 ? hostRef.current?.getBoundingClientRect?.() : null;
      return rect ?? rectRef.current;
    };
    const convert = (list: ArrayLike<RawTouch> | undefined): ChartTouch[] => {
      if (!list) return [];
      let o: { left: number; top: number } | undefined;
      return Array.from(list, (t, i) => {
        const identifier = t.identifier ?? i;
        // mini-programs: x / y relative to the canvas
        if (typeof t.x === "number" && typeof t.y === "number")
          return { x: t.x, y: t.y, identifier };
        o ??= origin();
        return {
          x: (t.clientX ?? 0) - o.left,
          y: (t.clientY ?? 0) - o.top,
          identifier,
        };
      });
    };
    const touch =
      (kind: "touchStart" | "touchMove" | "touchEnd" | "touchCancel") =>
      (event: unknown) => {
        const chart = chartRef.current;
        if (!chart) return;
        lastTouch = Date.now();
        const e = event as RawTouchEvent;
        const touches = convert(
          kind === "touchMove" ? e.touches : e.changedTouches,
        );
        if (kind === "touchCancel")
          chart.touchCancel(touches.length ? touches : undefined);
        else chart[kind](touches);
      };
    const mouse =
      (kind: "pointerDown" | "pointerMove" | "pointerUp") =>
      (event: unknown) => {
        const chart = chartRef.current;
        if (!chart || Date.now() - lastTouch < MOUSE_AFTER_TOUCH_MS) return;
        const e = event as RawMouseEvent;
        const o = origin();
        chart[kind](e.clientX - o.left, e.clientY - o.top);
      };
    return {
      onTouchStart: touch("touchStart"),
      onTouchMove: touch("touchMove"),
      onTouchEnd: touch("touchEnd"),
      onTouchCancel: touch("touchCancel"),
      // H5 on desktop: mouse hover / click
      ...(isH5
        ? {
            onMouseDown: mouse("pointerDown"),
            onMouseMove: mouse("pointerMove"),
            onMouseUp: mouse("pointerUp"),
            onMouseLeave: () => chartRef.current?.pointerLeave(),
          }
        : {}),
    };
  }, []);

  const canvasStyle = useMemo<CSSProperties>(
    () => ({
      display: "block",
      width: "100%",
      height: "100%",
      ...(disableScroll ? { touchAction: "none" } : {}),
    }),
    [disableScroll],
  );

  return (
    <View
      className={cn("mn-chart", "mn-shape-chart", className)}
      data-minerva="chart"
      {...{ role: "img" }}
      aria-label={options.ariaLabel ?? describe(options)}
      style={{
        position: "relative",
        width: toLength(width),
        height: toLength(height),
        ...style,
      }}
    >
      <Canvas
        ref={hostRef as never}
        type="2d"
        id={canvasId}
        className="mn-chart-canvas"
        style={canvasStyle}
        disableScroll={disableScroll}
        {...(canvasProps as Record<string, (event: never) => void>)}
      />
    </View>
  );
}

/** Engine options shared by every type, stable while the props are equal */
function useCommonOptions({
  palette,
  legend,
  tooltip,
  format,
  percentFormat,
  hidden,
  animation,
  padding,
  ariaLabel,
  locale,
  texts,
}: ShapeChartCommonProps): ShapeChartCommonOptions {
  // a new array with the same indexes keeps the options (and the animation)
  const hiddenKey = hidden ? hidden.join(",") : null;
  const stableHidden = useMemo(
    () =>
      hiddenKey === null
        ? undefined
        : hiddenKey
          ? hiddenKey.split(",").map(Number)
          : [],
    [hiddenKey],
  );
  return useMemo(
    () => ({
      palette,
      legend,
      tooltip,
      format,
      percentFormat,
      hidden: stableHidden,
      animation,
      padding,
      ariaLabel,
      locale,
      texts,
    }),
    [
      palette,
      legend,
      tooltip,
      format,
      percentFormat,
      stableHidden,
      animation,
      padding,
      ariaLabel,
      locale,
      texts,
    ],
  );
}

function ShapeHost({
  frame,
  options,
  defaultHeight,
  handleRef,
  onDrill,
}: {
  frame: ShapeChartFrameProps;
  options: ShapeChartOptions;
  defaultHeight: number;
  handleRef: ForwardedRef<ShapeChartHandle>;
  onDrill?: (event: ShapeDrillEvent) => void;
}) {
  const {
    height,
    width,
    className,
    style,
    id,
    disableScroll,
    onHover,
    onClick,
    onToggle,
  } = frame;
  return (
    <ShapeChartBase
      options={options}
      height={height ?? defaultHeight}
      width={width}
      className={className}
      style={style}
      id={id}
      disableScroll={disableScroll ?? false}
      handleRef={handleRef}
      onHover={onHover}
      onClick={onClick}
      onToggle={onToggle}
      onDrill={onDrill}
    />
  );
}

