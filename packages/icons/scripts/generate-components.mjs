// Writes src/react/icons.ts: one named React component per built-in icon
// (`searchIcon` -> `SearchIcon`), from the icon files of src/engine/icons.
// Run after adding or renaming an icon: pnpm --filter @minerva/icons gen
// (a unit test fails while the file is out of date).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const iconsDir = join(root, "src/engine/icons");
const output = join(root, "src/react/icons.ts");

const ORDER = [
  "arrows",
  "actions",
  "interface",
  "media",
  "files",
  "communication",
  "data",
  "finance",
  "status",
  "devices",
];

const rank = (file) => {
  const index = ORDER.indexOf(file);
  return index < 0 ? ORDER.length : index;
};

const files = readdirSync(iconsDir)
  .filter((file) => file.endsWith(".ts") && file !== "index.ts")
  .map((file) => file.replace(/\.ts$/, ""))
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));

const constants = files.flatMap((file) =>
  [
    ...readFileSync(join(iconsDir, `${file}.ts`), "utf8").matchAll(
      /^export const (\w+Icon): IconDefinition/gm,
    ),
  ].map((match) => match[1]),
);

const component = (constant) =>
  constant.charAt(0).toUpperCase() + constant.slice(1);

const source = [
  "// Generated by scripts/generate-components.mjs: do not edit.",
  "// One React component per built-in icon; unused ones are tree-shaken.",
  'import * as icons from "../engine/icons";',
  'import { createIcon } from "./createIcon";',
  "",
  ...constants.map(
    (constant) =>
      `export const ${component(constant)} = /* @__PURE__ */ createIcon(icons.${constant});`,
  ),
  "",
].join("\n");

const config = (await prettier.resolveConfig(output)) ?? {};
writeFileSync(
  output,
  await prettier.format(source, { ...config, filepath: output }),
);
process.stdout.write(`${constants.length} icon components -> ${output}\n`);
