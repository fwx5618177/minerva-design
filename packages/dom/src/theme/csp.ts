/**
 * Content-Security-Policy support for the inline theme init script.
 *
 * A strict CSP (`script-src 'nonce-…'` or `'sha256-…'`, no
 * `'unsafe-inline'`) blocks an inline `<script>` unless it carries the
 * request's nonce or its hash is listed. Either render
 * `<script nonce={nonce}>` with the script, or list the script's hash:
 *
 *   Content-Security-Policy: script-src 'self' ${THEME_INIT_SCRIPT_HASH}
 *
 * `cspHash()` computes it for a custom `createThemeInitScript(...)` output
 * (synchronous and dependency-free, so it works in every server runtime).
 */
import { THEME_INIT_SCRIPT } from "./cookies";

